package io.hexlet.spring.service.impl;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicLong;

import org.springframework.stereotype.Service;

import io.hexlet.spring.dto.UserRequest;
import io.hexlet.spring.dto.UserResponse;
import io.hexlet.spring.exception.ResourceNotFoundException;
import io.hexlet.spring.service.UserService;

/**
 * Users are kept in memory (LR5 demonstrates API documentation, the DB schema is not changed).
 * Identifiers are generated by a counter: "1", "2", ...
 */
@Service
public class UserServiceImpl implements UserService {

    private final Map<String, UserResponse> users = new ConcurrentHashMap<>();
    private final AtomicLong sequence = new AtomicLong();

    @Override
    public List<UserResponse> getAll() {
        var result = new ArrayList<>(users.values());
        result.sort(Comparator.comparingLong(user -> Long.parseLong(user.getId())));
        return result;
    }

    @Override
    public UserResponse create(UserRequest request) {
        var id = String.valueOf(sequence.incrementAndGet());
        var user = new UserResponse(id, request.getName(), request.getEmail());
        users.put(id, user);
        return copy(user);
    }

    @Override
    public UserResponse findById(String userId) {
        var user = users.get(userId);
        if (user == null) {
            throw new ResourceNotFoundException("User with id " + userId + " not found");
        }
        return copy(user);
    }

    private static UserResponse copy(UserResponse user) {
        return new UserResponse(user.getId(), user.getName(), user.getEmail());
    }
}
